CREATE TABLE BOOK_CATEGORIES
(
    BOOK_ID INT NOT NULL,
    CATEGORY_ID INT NOT NULL,

    PRIMARY KEY(BOOK_ID, CATEGORY_ID),

    FOREIGN KEY(BOOK_ID)
        REFERENCES BOOKS(BOOK_ID)
        ON DELETE CASCADE,

    FOREIGN KEY(CATEGORY_ID)
        REFERENCES CATEGORIES(CATEGORY_ID)
        ON DELETE CASCADE
);
CREATE TABLE CART_ITEMS(
	CART_ID INT NOT NULL,
	BOOK_ID INT NOT NULL,
	QUANTITY INT NOT NULL CHECK(QUANTITY > 0),
	
	PRIMARY KEY(CART_ID, BOOK_ID),
	
	FOREIGN KEY (CART_ID)
		REFERENCES CARTS(CART_ID)
		ON DELETE CASCADE,
		
	FOREIGN KEY(BOOK_ID) 
		REFERENCES BOOKS(BOOK_ID)
		ON DELETE RESTRICT
);